    s = s.replace(/"[^"\n]*"/g, function (q) { keep.push(q); return '\u0001' + (keep.length - 1) + '\u0002'; });
    for (var i = 0; i < KEYS.length; i++) { var k = KEYS[i]; if (s.indexOf(k) >= 0) s = s.split(k).join(D[k]); if (!HI.test(s)) break; }
